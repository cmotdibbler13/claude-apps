// Copies Autocue Studio's join files into js/autocue-bundle.js, so Studio can install them on Jon's PC.
// Run after changing autocue-studio/voiceover_join.py or line_script.py:  node scripts/embed-autocue.mjs
// tests/autocueinstall.test.mjs fails while the bundle is behind the repo files.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "autocue-studio");
export const BUNDLED = ["voiceover_join.py", "line_script.py"];
const files = Object.fromEntries(BUNDLED.map((f) => [f, readFileSync(join(src, f), "utf8").replace(/\r\n/g, "\n")]));
const out = `// Generated by scripts/embed-autocue.mjs from autocue-studio/. Do not edit by hand.
export const AUTOCUE_FILES = ${JSON.stringify(files, null, 0)};
`;
writeFileSync(join(here, "..", "js", "autocue-bundle.js"), out);
console.log(`Wrote js/autocue-bundle.js (${BUNDLED.join(", ")})`);
